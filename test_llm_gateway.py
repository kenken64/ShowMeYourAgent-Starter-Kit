"""## 4) Run

Manual tool-call loop: the gateway has no native tool support, so the model
emits a JSON tool request which we parse and execute ourselves.
"""

import json
import re

def extract_tool_call(text: str):
    """Return {"tool": ..., "args": {...}} if the model emitted a tool request."""
    match = re.search(r'\{.*"tool".*\}', text, re.DOTALL)
    if not match:
        return None
    try:
        payload = json.loads(match.group(0))
    except json.JSONDecodeError:
        return None
    if payload.get("tool") and isinstance(payload.get("args"), dict):
        return payload
    return None

import time

def invoke_with_retry(messages, max_retries=5, backoff=3):
    """Retry llm.invoke on transient gateway errors (ALB rate-limits rapid successive calls)."""
    for attempt in range(1, max_retries + 1):
        try:
            return llm.invoke(messages)
        except Exception as e:
            if attempt == max_retries:
                raise
            wait = backoff * attempt
            print(f">>> Attempt {attempt} failed ({type(e).__name__}), retrying in {wait}s...")
            time.sleep(wait)

def run_agent(user_msg: str):
    messages = [
        {"role": "system", "content": SYSTEM},
        {"role": "user", "content": user_msg},
    ]
    for _ in range(4):  # max iterations
        reply = invoke_with_retry(messages)
        tool_req = extract_tool_call(reply.content)
        if not tool_req:
            return reply.content  # final answer
        print(f">>> Tool request: {tool_req}")
        result = estimate_trip_cost.invoke(tool_req["args"])
        print(f">>> Tool result: {result}")
        messages.append({"role": "assistant", "content": reply.content})
        messages.append({"role": "user", "content": f"Tool result: {json.dumps(result)}\nNow present the estimate to the user."})
    return "Max tool-call iterations reached."

msg = "Plan a 2-day Tokyo trip for 2 adults. Mid comfort. how much will be the cost"
print(run_agent(msg))

